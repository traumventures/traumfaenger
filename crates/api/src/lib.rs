/// Routes. Ingestion and query routes are served on different listeners.
pub mod routes {
    /// `GET`, unauthenticated, on both listeners.
    pub const HEALTH: &str = "/health";
    /// Ingestion listener: WebSocket upgrade for streaming batches.
    pub const INGEST_WS: &str = "/v1/ingest";
    /// Ingestion listener: `POST` one batch as `{ "exchanges": [...] }` (JSON).
    pub const INGEST_HTTP: &str = "/v1/exchanges";
    /// Query listener: `GET` a filtered page of raw log rows, newest first.
    pub const LIST_EXCHANGES: &str = "/v1/exchanges";
    /// Query listener: `GET` one exchange with all its segments and frames.
    pub const GET_EXCHANGE: &str = "/v1/exchanges/{id}";
    /// Query listener: `GET` collection statistics grouped by dimensions.
    pub const SUMMARY: &str = "/v1/summary";
}

/// WebSocket subprotocols of the ingestion socket. The client offers them in
/// its order of preference; the server picks MessagePack when offered.
pub mod protocols {
    /// Text messages carrying JSON.
    pub const JSON: &str = "ai-ledger.v1.json";
    /// Binary messages carrying MessagePack (maps with field names).
    pub const MSGPACK: &str = "ai-ledger.v1.msgpack";
}

/// Limits enforced by the server. Exported to TypeScript as `LIMITS`.
pub mod limits {
    /// Maximum number of exchanges in one batch.
    pub const MAX_BATCH_SIZE: usize = 500;
    /// Maximum size of one batch: a WebSocket message, or an HTTP body after
    /// gzip decompression.
    pub const MAX_BATCH_BYTES: usize = 32 * 1024 * 1024;
    /// Batches the server accepts before acknowledging; more wait.
    pub const MAX_IN_FLIGHT_BATCHES: usize = 4;
    pub const MAX_ID_LEN: usize = 128;
    /// Maximum length of `service`, `environment`, `operation` and `session_id`.
    pub const MAX_NAME_LEN: usize = 256;
    pub const MAX_URL_LEN: usize = 2_048;
    /// Maximum number of frames in one exchange record (one segment).
    pub const MAX_FRAMES: usize = 10_000;
    /// Maximum size of one frame's `data`, in bytes.
    pub const MAX_FRAME_BYTES: usize = 4 * 1024 * 1024;
    /// Maximum size of all frames of one record together, in bytes.
    pub const MAX_RECORD_BYTES: usize = 8 * 1024 * 1024;
    /// Highest segment number of a WebSocket exchange.
    pub const MAX_SEGMENT: u32 = 100_000;
    pub const MAX_ERROR_LEN: usize = 4_000;
    pub const MAX_METADATA_ENTRIES: usize = 32;
    pub const MAX_METADATA_KEY_LEN: usize = 64;
    pub const MAX_METADATA_VALUE_LEN: usize = 512;
    /// Upper bound for every `t_ms` and `at_ms`: one day.
    pub const MAX_DURATION_MS: u64 = 86_400_000;
    /// Default and maximum page size of the list endpoint.
    pub const DEFAULT_LIST_LIMIT: u32 = 100;
    pub const MAX_LIST_LIMIT: u32 = 1_000;
    /// Default and maximum number of rows of `GET /v1/summary`.
    pub const DEFAULT_SUMMARY_LIMIT: u32 = 1_000;
    pub const MAX_SUMMARY_LIMIT: u32 = 10_000;
}

/// How the exchange went over the wire.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum Transport {
    /// One request body, one response body.
    Http,
    /// One request body, then one frame per server-sent event.
    Sse,
    /// One frame per WebSocket message, in both directions.
    Ws,
}

impl Transport {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Http => "http",
            Self::Sse => "sse",
            Self::Ws => "ws",
        }
    }

    pub fn parse(value: &str) -> Option<Self> {
        [Self::Http, Self::Sse, Self::Ws].into_iter().find(|transport| transport.as_str() == value)
    }
}

#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum Direction {
    /// From the client to the provider.
    Out,
    /// From the provider to the client.
    In,
}

/// One unit on the wire: a request or response body, an SSE event, or a
/// WebSocket message. `data` is verbatim text; clients replace binary data
/// and inline base64 payloads with a short placeholder.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize, TS)]
pub struct Frame {
    /// Milliseconds since `started_at` when the frame was sent or complete.
    #[ts(type = "number")]
    pub t_ms: u64,
    pub dir: Direction,
    pub data: String,
}

#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(rename_all = "snake_case")]
pub enum EndReason {
    /// The response or stream finished normally.
    Complete,
    /// A network or protocol error, see `error`.
    Error,
    /// The caller cancelled the stream.
    Cancelled,
    /// The WebSocket closed, see `close_code`.
    Closed,
}

impl EndReason {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Complete => "complete",
            Self::Error => "error",
            Self::Cancelled => "cancelled",
            Self::Closed => "closed",
        }
    }

    pub fn parse(value: &str) -> Option<Self> {
        [Self::Complete, Self::Error, Self::Cancelled, Self::Closed].into_iter().find(|reason| reason.as_str() == value)
    }
}

/// How and when an exchange ended.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize, TS)]
pub struct ExchangeEnd {
    /// Milliseconds since `started_at`.
    #[ts(type = "number")]
    pub at_ms: u64,
    pub reason: EndReason,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub error: Option<String>,
    /// WebSocket close code.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub close_code: Option<u16>,
}

