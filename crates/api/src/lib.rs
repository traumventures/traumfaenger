/// One exchange with an AI provider, as recorded by a client.
///
/// Only what is not on the wire is sent as a separate field; models, usage,
/// cost, messages and tool calls are derived later from the frames.
///
/// Long WebSocket sessions are sent in segments while they run: records with
/// the same `id`, `segment` counting up from 0 and `final` only on the last.
/// `(id, segment)` is the idempotency key: re-sending a stored record is
/// accepted, counted as a duplicate and changes nothing. Unknown fields are
/// ignored, so a newer client can talk to an older server.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize, TS)]
pub struct Exchange {
    /// Client-generated unique id, for example a UUID. 1–128 bytes.
    pub id: String,
    /// 0 unless a WebSocket session is sent in parts.
    #[serde(default, skip_serializing_if = "is_zero")]
    #[ts(optional, as = "Option<u32>")]
    pub segment: u32,
    /// False on every segment but the last. Defaults to true.
    #[serde(rename = "final", default = "yes", skip_serializing_if = "is_true")]
    #[ts(rename = "final", optional, as = "Option<bool>")]
    pub is_final: bool,
    /// The emitting service, for example `traumwohnung-web`.
    pub service: String,
    /// For example `production`, `dev` or `local`.
    pub environment: String,
    /// The kind of work, for example `listing.parse`.
    pub operation: String,
    /// Groups the exchanges of one conversation, for example one support chat.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub session_id: Option<String>,
    /// Flat key-value pairs, for example `{ "listing_id": "123" }`. At most 32
    /// entries; keys are 1–64 characters of `A-Z a-z 0-9 _ . -`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional, type = "Record<string, string>")]
    pub metadata: Option<BTreeMap<String, String>>,
    pub transport: Transport,
    /// The request URL. The server drops query string and fragment.
    pub url: String,
    /// When the exchange started, RFC 3339. The same for every segment.
    #[ts(type = "string")]
    pub started_at: DateTime<Utc>,
    /// HTTP status of the response; 101 once a WebSocket is open. Absent
    /// when no response arrived.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub status: Option<u16>,
    /// The frames of this record, in wire order. For HTTP and SSE the request
    /// body is the first `out` frame.
    pub frames: Vec<Frame>,
    /// Present exactly on final records.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub end: Option<ExchangeEnd>,
    /// True when the client changed anything to fit the limits: clipped or
    /// dropped frames, or cleaned context (invalid metadata entries dropped,
    /// values clipped, an empty operation recorded as `unattributed`).
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    #[ts(optional, as = "Option<bool>")]
    pub truncated: bool,
}

impl Exchange {
    /// Checks every field against [`limits`]. Returns a human-readable reason.
    pub fn validate(&self) -> Result<(), String> {
        check_line("id", &self.id, limits::MAX_ID_LEN)?;
        check_line("service", &self.service, limits::MAX_NAME_LEN)?;
        check_line("environment", &self.environment, limits::MAX_NAME_LEN)?;
        check_line("operation", &self.operation, limits::MAX_NAME_LEN)?;
        if let Some(session_id) = &self.session_id {
            check_line("session_id", session_id, limits::MAX_NAME_LEN)?;
        }
        if let Some(metadata) = &self.metadata {
            check_metadata(metadata)?;
        }
        check_line("url", self.stored_url(), limits::MAX_URL_LEN)?;
        if !["https://", "http://", "wss://", "ws://"].iter().any(|scheme| self.url.starts_with(scheme)) {
            return Err("url must be an http(s) or ws(s) URL".into());
        }
        if self.transport != Transport::Ws && (self.segment != 0 || !self.is_final) {
            return Err("only ws exchanges can be sent in segments".into());
        }
        if self.segment > limits::MAX_SEGMENT {
            return Err(format!("segment must be at most {}", limits::MAX_SEGMENT));
        }
        if self.status.is_some_and(|status| !(100..=599).contains(&status)) {
            return Err("status must be between 100 and 599".into());
        }
        self.check_frames()?;
        match (&self.end, self.is_final) {
            (Some(end), true) => self.check_end(end),
            (None, false) => Ok(()),
            (None, true) => Err("a final record needs `end`".into()),
            (Some(_), false) => Err("only the final record has `end`".into()),
        }
    }

    fn check_frames(&self) -> Result<(), String> {
        if self.frames.len() > limits::MAX_FRAMES {
            return Err(format!("at most {} frames per record", limits::MAX_FRAMES));
        }
        let mut total = 0usize;
        let mut previous = 0u64;
        for (index, frame) in self.frames.iter().enumerate() {
            if frame.data.len() > limits::MAX_FRAME_BYTES {
                return Err(format!("frames[{index}].data must be at most {} bytes", limits::MAX_FRAME_BYTES));
            }
            total += frame.data.len();
            if frame.t_ms > limits::MAX_DURATION_MS {
                return Err(format!("frames[{index}].t_ms must be at most {}", limits::MAX_DURATION_MS));
            }
            if frame.t_ms < previous {
                return Err(format!("frames[{index}].t_ms must not decrease"));
            }
            previous = frame.t_ms;
        }
        if total > limits::MAX_RECORD_BYTES {
            return Err(format!("frames must be at most {} bytes together", limits::MAX_RECORD_BYTES));
        }
        Ok(())
    }

    fn check_end(&self, end: &ExchangeEnd) -> Result<(), String> {
        if end.at_ms > limits::MAX_DURATION_MS {
            return Err(format!("end.at_ms must be at most {}", limits::MAX_DURATION_MS));
        }
        if self.frames.last().is_some_and(|frame| frame.t_ms > end.at_ms) {
            return Err("end.at_ms must not be before the last frame".into());
        }
        if let Some(error) = &end.error
            && (error.trim().is_empty() || error.len() > limits::MAX_ERROR_LEN)
        {
            return Err(format!("end.error must be 1–{} bytes", limits::MAX_ERROR_LEN));
        }
        if end.close_code.is_some() && self.transport != Transport::Ws {
            return Err("end.close_code is only for ws exchanges".into());
        }
        Ok(())
    }

    /// `url` without query string and fragment, which can carry API keys.
    pub fn stored_url(&self) -> &str {
        let end = self.url.find(['?', '#']).unwrap_or(self.url.len());
        &self.url[..end]
    }

    /// Total bytes of frame data.
    pub fn data_bytes(&self) -> usize {
        self.frames.iter().map(|frame| frame.data.len()).sum()
    }
}

fn check_line(name: &str, value: &str, max: usize) -> Result<(), String> {
    if value.trim().is_empty() {
        return Err(format!("{name} must not be empty"));
    }
    if value.len() > max {
        return Err(format!("{name} must be at most {max} bytes"));
    }
    if value.chars().any(char::is_control) {
        return Err(format!("{name} must not contain control characters"));
    }
    Ok(())
}

fn check_metadata(metadata: &BTreeMap<String, String>) -> Result<(), String> {
    if metadata.len() > limits::MAX_METADATA_ENTRIES {
        return Err(format!("metadata must have at most {} entries", limits::MAX_METADATA_ENTRIES));
    }
    for (key, value) in metadata {
        let valid_key = (1..=limits::MAX_METADATA_KEY_LEN).contains(&key.len())
            && key.bytes().all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'.' | b'-'));
        if !valid_key {
            return Err(format!(
                "metadata key `{key}` must be 1–{} characters of A-Z a-z 0-9 _ . -",
                limits::MAX_METADATA_KEY_LEN
            ));
        }
        if value.len() > limits::MAX_METADATA_VALUE_LEN || value.contains('\0') {
            return Err(format!(
                "metadata value of `{key}` must be at most {} bytes without NUL",
                limits::MAX_METADATA_VALUE_LEN
            ));
        }
    }
    Ok(())
}

/// Message from the client on the ingestion socket.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize, TS)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ClientMessage {
    /// Up to 500 exchanges. Each is validated on its own: invalid ones are
    /// reported in the ack, the valid ones are stored.
    Batch {
        /// Chosen by the client, echoed in the ack.
        #[ts(type = "number")]
        id: u64,
        exchanges: Vec<Exchange>,
    },
}

/// Message from the server on the ingestion socket. Batches are acknowledged
/// in the order they were sent; a batch without ack was not stored and can
/// be resent.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize, TS)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ServerMessage {
    Ack {
        #[ts(type = "number")]
        batch: u64,
        #[serde(flatten)]
        result: IngestResult,
    },
    /// The batch as a whole was not usable, for example too many exchanges.
    /// Resending it unchanged will fail again.
    Error {
        #[ts(type = "number | null")]
        batch: Option<u64>,
        error: ErrorCode,
        message: String,
    },
}

/// Body of `POST /v1/exchanges` (JSON, optionally gzip-compressed).
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize, TS)]
