//! The ai-ledger wire contract.
//!
//! ai-ledger records AI provider traffic in two steps:
//!
//! 1. **Ingestion** (this version): clients record every exchange with a
//!    provider (an HTTP call, an SSE stream or a WebSocket session) in one
//!    canonical shape, [`Exchange`]: an ordered list of timestamped [`Frame`]s
//!    as they went over the wire, plus the context that is not on the wire.
//!    The server appends them unparsed to its raw log.
//! 2. **Processing** (later): projections extract models, usage, cost,
//!    messages, tool calls and timings from the raw log into derived tables.
//!
//! Clients send exchanges over a WebSocket ([`routes::INGEST_WS`]) whose
//! encoding, JSON or MessagePack, is negotiated as a subprotocol (see
//! [`protocols`]). The same records can also be posted over HTTP. A separate,
//! read-only query API runs on its own listener with its own token.
//!
//! Every type that crosses the boundary is defined here once; the TypeScript
//! packages use declarations generated by [`typescript_bindings`].

use std::collections::BTreeMap;

use chrono::{DateTime, Utc};
use serde::{Deserialize, Deserializer, Serialize};
use ts_rs::TS;

